export const roundByKey = key => ROUND_TEMPLATES.find(item => item.key === key) || null;

export const roundRevenue = round =>
  round.legs.reduce((sum, leg) => sum + (leg.rate || 0), 0);

export const roundKm = round =>
  round.legs.reduce((sum, leg) => sum + (leg.km || 0), 0);

// Сколько машин нужно на объём шаблона при заданном зазоре стыковки между
// плечами (дней). Факт августа — 0,85 дня на плечо, цель — 0,33 (8 часов).
export function roundVehicles(round, gapDays = 0.85) {
  const loadedLegs = round.legs.filter(leg => leg.kind !== 'П').length;
  const kmDays = roundKm(round) / 538;
  return round.volume * (kmDays + loadedLegs * gapDays) / 30;
}
